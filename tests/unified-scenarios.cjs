// Behavioral checks for the merged private check, review gate and session data.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const memory = {};
const input = {};
const element = () => ({innerHTML: '', hidden: true, textContent: '', addEventListener() {}, querySelector() { return null; }});
const elements = Object.fromEntries(['view', 'notice', 'langToggle', 'patientFeedback'].map(key => [key, element()]));
const ctx = vm.createContext({document: {getElementById: key => input[key] || elements[key] || null, querySelectorAll: () => [], documentElement: {}}, window: {addEventListener() {}}, localStorage: {getItem: key => memory[key] || null, setItem: (key, value) => memory[key] = value}, navigator: {}, setInterval() {}, Date, Intl});
for (const file of ['i18n.js', 'state.js', 'videos.js', 'journey.js', 'learn-visual.js', 'chat.js']) vm.runInContext(fs.readFileSync(path.join(root, 'js', file), 'utf8'), ctx, {filename: file});
let app = fs.readFileSync(path.join(root, 'js/app.js'), 'utf8');
app = app.replace('  Store.init();', `globalThis.api = {Store, I18N, SirrJourney, go, handleAction, publish, renderClinician, chatScreen, learningCard, getAnswers: () => quizAnswers, setRole: value => {role = value;}, getLearning: () => learning, getChat: () => chat}; Store.init();`);
vm.runInContext(app, ctx);
const {Store, I18N, SirrJourney, handleAction, go, setRole, publish, renderClinician, chatScreen, getLearning, getChat, getAnswers} = ctx.api;
const route = values => SirrJourney.route(values).key;
go('learn');
assert(elements.view.innerHTML.includes('Three parts of the picture.'));
handleAction('explore-stage', {dataset: {stage: '2'}});
assert(elements.view.innerHTML.includes('There is a pathway out.'));
handleAction('explore-question', {dataset: {}});
assert.equal(getChat().messages[0].text, I18N.t('visualPathwayQuestion'));
assert.equal(getChat().messages[1].topic, 'pathway');
handleAction('exit-session', {dataset: {}});
assert.equal(route([1]), 'emergency');
assert.equal(route([2]), 'urgent');
assert.equal(route([3,0,0,0,2]), 'doctor');
assert.equal(route([0,3,0,0,2]), 'doctor');
assert.equal(route([0,0,0,1,2]), 'doctor');
assert.equal(route([0,0,2,0,2]), 'assessment');
assert.equal(route([0,0,0,0,2]), 'learn');
assert.equal(route([0,0,0,0,0]), 'assessment');
assert.equal(route([0,0,0,0,1]), 'doctor');
handleAction('goto-quiz', {dataset: {}});
handleAction('quiz-answer', {dataset: {value: '1'}});
assert.equal(getAnswers()[0], 1);
handleAction('quiz-next', {dataset: {}});
assert.match(elements.view.innerHTML, /Please seek emergency care now/);
assert(!elements.view.innerHTML.includes('data-action="goto-overview"'));
go('chat');
assert.equal(getAnswers().length, 0, 'Private answers clear when opening chat');
input['chat-input'] = {value: '<img src=x onerror=alert(1)>'};
handleAction('chat-send', {dataset: {}});
assert(chatScreen().includes('&lt;img'));
assert(!chatScreen().includes('<img src=x'));
assert(!JSON.stringify(Store.data).includes('onerror'), 'Chat never enters persisted app data');
handleAction('chat-clear', {dataset: {}});
assert.equal(getChat().messages.length, 0);
handleAction('chat-suggest', {dataset: {prompt: 'starterTest'}});
assert.equal(getChat().messages[1].topic, 'test');
handleAction('exit-session', {dataset: {}});
assert.equal(getChat().messages.length, 0);
assert.equal(getAnswers().length, 0);
Store.loadDemoScenario('prepare');
const sample = Store.data.samples.find(s => s.demoScenario === 'prepare');
assert.equal(Store.transition(sample.id, 'lab_received'), null, 'Cannot skip courier stages');
Store.update(sample.id, {collectedAt: new Date().toISOString(), sealOk: true});
Store.dispatch(sample.id);
for (const status of ['picked_up', 'in_transit', 'lab_received']) assert(Store.transition(sample.id, status));
setRole('lab');
Store.update(sample.id, {accepted: true});
const fixture = {volume: '2.8', concentration: '18', count: '50.4', totalMotility: '36', progressiveMotility: '29', morphology: '3', velocity: '31'};
for (const [key, value] of Object.entries(fixture)) input['p-' + key] = {value};
input['p-totalMotility'].value = '101';
publish(sample);
assert.equal(sample.status, 'lab_received', 'Invalid percentages cannot enter review');
input['p-totalMotility'].value = '36';
publish(sample);
assert.equal(sample.status, 'analysed');
assert.equal(sample.publishedAt, null);
assert(!Store.data.samples.filter(s => s.status === 'results_ready').includes(sample));
assert(renderClinician().includes(sample.id));
go('report', sample.id);
assert(!elements.view.innerHTML.includes('review-patient-note'), 'Pending report is not rendered to patient');
assert.equal(Store.approveReport(sample.id, '', 'en'), null);
assert(Store.approveReport(sample.id, 'Synthetic clinician review note', 'en'));
assert.equal(sample.status, 'results_ready');
assert(sample.review.at && sample.publishedAt);
assert.equal(Store.approveReport(sample.id, 'again', 'en'), null, 'Approval is not repeated');
assert.equal(Store.transition(sample.id, 'picked_up'), null, 'Released reports cannot re-enter dispatch');
const review = Store.loadDemoScenario('review');
assert.equal(review.status, 'analysed');
assert.equal(review.publishedAt, null);
assert(review.results && review.accepted);
for (const lang of ['en', 'ar']) {
 I18N.set(lang);
 for (const q of SirrJourney.questions) {
  assert.notEqual(I18N.t(q.title), q.title);
  assert.notEqual(I18N.t(q.hint), q.hint);
  for (const [key] of q.options) assert.notEqual(I18N.t(key), key);
 }
}
assert.deepEqual(Object.keys(I18N.en).filter(key => !I18N.ar[key]), []);
console.log('PASS: routing, urgent bypass, answer clearing, chat escaping/privacy, valid handoffs, invalid measurement rejection, clinician-only release path, repeat-safe approval and bilingual check-in.');
